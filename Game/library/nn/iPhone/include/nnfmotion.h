/* Submotion interpolate type for scalar */
#define	NND_SMOTIPTYPE_SPLINE		( (Uint32)1 << 0 )	/* ３次スプライン補間 */
#define	NND_SMOTIPTYPE_LINEAR		( (Uint32)1 << 1 )	/* 線形補間 */
