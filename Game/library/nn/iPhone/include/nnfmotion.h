#define	NND_SMOTIPTYPE_BEZIER		( (Uint32)1 << 4 )	/* ベジェスプライン補間 */
#define	NND_SMOTIPTYPE_SI_SPLINE	( (Uint32)1 << 5 )	/* SIスプライン補間 */
#define	NND_SMOTIPTYPE_TRIGGER		( (Uint32)1 << 6 )	/* トリガ */

/* Submotion interpolate type for 3D-angle */
#define	NND_SMOTIPTYPE_QUAT_LERP	( (Uint32)1 << 9 )	/* クォータニオン線形補間 */
#define	NND_SMOTIPTYPE_QUAT_SLERP	( (Uint32)1 << 10 )	/* クォータニオン球面線形補間 */
#define	NND_SMOTIPTYPE_QUAT_SQUAD	( (Uint32)1 << 11 )	/* クォータニオン球面３次スプライン補間 */

#define	NND_SMOTIPTYPE_IP_MASK	\
	( NND_SMOTIPTYPE_SPLINE | NND_SMOTIPTYPE_LINEAR | NND_SMOTIPTYPE_CONSTANT |	\
	NND_SMOTIPTYPE_BEZIER | NND_SMOTIPTYPE_SI_SPLINE | NND_SMOTIPTYPE_TRIGGER | \
	NND_SMOTIPTYPE_QUAT_LERP | NND_SMOTIPTYPE_QUAT_SLERP | NND_SMOTIPTYPE_QUAT_SQUAD )

