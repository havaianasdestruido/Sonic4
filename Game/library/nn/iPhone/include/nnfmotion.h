/* Submotion type */
typedef Uint32	NNF_SUBMOTION_TYPE;

/* Submotion interpolate-repeat type */
typedef Uint32	NNF_SMOTIPTYPE;

/* Submotion */
typedef struct {
	NNF_SUBMOTION_TYPE	fType;			/* サブモーションのタイプ */
	NNF_SMOTIPTYPE		fIPType;		/* 補間、リピートタイプ */
	union {
		Sint32			Id;				/* サブモーションID、適用先 */
		struct {
			Sint16		Id0;			/* サブモーションサブID0 適用先 */
			Sint16		Id1;			/* サブモーションサブID1 適用先 */
		};
	};
	Float				StartFrame;		/* このサブモーション最初のフレーム */
	Float				EndFrame;		/* このサブモーション最後のフレーム */
	Float				StartKeyFrame;	/* 最初のキーのフレーム */
	Float				EndKeyFrame;	/* 最初のキーのフレーム */
	Sint32				nKeyFrame;		/* キーフレームの数 */
	Sint32				KeySize;		/* キーフレームデータサイズ */
	void				*pKeyList;		/* モーションキーリストへのポインタ */
} NNS_SUBMOTION;


/**********/
/* Motion */
/**********/

/* Motion type */
typedef Uint32	NNF_MOTIONTYPE;

/* Motion (Version2) */
typedef struct {
	NNF_MOTIONTYPE		fType;			/* モーションのタイプ */
	Float				StartFrame;		/* モーションの最初のフレーム番号 */
	Float				EndFrame;		/* モーションの最後のフレーム番号 */
	Sint32				nSubmotion;		/* サブモーションの数 */
	NNS_SUBMOTION		*pSubmotion;	/* サブモーションリストポインタ */
	Float				FrameRate;		/* フレームレート（V2パラメータ） */
	Uint32				Reserved0;		/* 予約（V2パラメータ） */
	Uint32				Reserved1;		/* 予約（V2パラメータ） */
} NNS_MOTION;
/* fType に NND_MOTIONTYPE_VERSION2 のビットが立っていないときに */
/* FrameRate, Reserved0, Reserved1 へのアクセスは禁止            */


