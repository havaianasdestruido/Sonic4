#define	NND_SMOTIPTYPE_REPEAT		( (Uint32)1 << 18 )	/* リピート */
#define	NND_SMOTIPTYPE_MIRROR		( (Uint32)1 << 19 )	/* ミラーリピート */
#define	NND_SMOTIPTYPE_OFFSET		( (Uint32)1 << 20 )	/* オフセットリピート No support */

