/*--- Definitions -----------------------------------------------------------*/

#define AMD_USE_PERFORMANCE_COUNTER			(_PC | _XBOX | _IPHONE)

// 計測タイマー
typedef struct {
	Uint64		count_start;		// スタートカウンタ
	Uint64		count_end;			// エンドカウンタ
	Sint32		delete_flag;		// メモリ解放フラグ
	float		count_freq;			// カウンタ精度(秒)
	float		frame;				// フレーム(1/60秒)
	float		msec;				// ミリ秒(1/1000秒)
	float		usec;				// マイクロ秒(1/1000000秒)
} AMS_TIMER;


// 周期タイマー
typedef struct {
	Sint32		delete_flag;		// メモリ解放フラグ
	Uint32		alarm_id;			// アラーム識別ID
#if _PC | _XBOX
#if AMD_USE_PERFORMANCE_COUNTER
	HANDLE		handle;
	float		count_freq;			// カウンタ精度(秒)
	Uint64		count_start;		// スタートカウンタ
	Uint64		count_end;			// エンドカウンタ
	Uint64		count_interval;		// カウンタインターバル
	AMS_MUTEX	mutex;
#else
	HANDLE		handle;
	HANDLE		handle_vsync;
#endif
#elif _PS3
	sys_timer_t	timer;
	sys_event_port_t	port;
	sys_event_queue_t	event;
#elif _WII
	OSAlarm		alarm;				// アラーム
	OSSemaphore	sema;				// セマフォ
#elif _IPHONE
	Uint32		timer_id;
	struct sigaction	action;
	struct sigevent		event;
	struct itimerval	tspec;
	sem_t		sema;
#if AMD_USE_PERFORMANCE_COUNTER
	AMS_TIMER	timer;
	Uint64		count_end;
	Uint64		count_interval;
#endif
#endif
} AMS_ALARM;


