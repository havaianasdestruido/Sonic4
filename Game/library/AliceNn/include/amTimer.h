/*****************************************************************************/
/* float amTimerGetFrame(AMS_TIMER *timer)                                   */
/*---------------------------------------------------------------------------*/
/* [INPUT]  timer : タイマー構造体                                           */
/* [RETURN] 経過時間(1/60秒単位)                                             */
/* [FUNCTION]  タイマー計測の結果                                            */
/*****************************************************************************/
