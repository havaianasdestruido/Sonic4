// ***************************************************************************
// パッド状態
// ***************************************************************************
// ===========================================================================
//! 指定ポートにパッドが接続されているか判定
// ===========================================================================
BOOL AoPadIsConnected(u32 port)
{
	if (PAD_CONNECT(port)) {
		return TRUE;
	}
	return FALSE;
}

// ===========================================================================
//! カレントユーザのパッドが接続されているか判定
// ===========================================================================
BOOL AoPadIsConnected(void)
{
	s32 id = AoAccountGetCurrentId();
	if (id < 0) {
		return FALSE;
	}
	return AoPadIsConnected((u32)id);
}


// ***************************************************************************
// バイブレーション
// ***************************************************************************
// ===========================================================================
//! バイブレーションの有効/無効設定						amPadEnableVibration
// ===========================================================================
void AoPadEnableVibration(BOOL flag)
{
	if ((u32)AoAccountGetCurrentId() < AOD_PAD_PORT_MAX) {
		amPadEnableVibration((s32)AoAccountGetCurrentId(), (s32)flag);
	}
	else {
		amAssert(0);
	}
}

// ===========================================================================
//! バイブレーションの設定									amPadSetVibration
// ===========================================================================
void AoPadSetVibration(u16 left, u16 right)
{
#if defined(AOD_PLATFORM_WII)
	// HBM表示時は振動を無効にする
	if (amWiiIsDrawHBM()) {
		left = 0;
		right = 0;
	}
#endif // defined(AOD_PLATFORM_WII)

	if ((u32)AoAccountGetCurrentId() < AOD_PAD_PORT_MAX) {
		amPadSetVibration((s32)AoAccountGetCurrentId(), left, right);
	}
	else {
		amAssert(0);
	}
}

