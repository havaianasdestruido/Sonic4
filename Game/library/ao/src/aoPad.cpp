// ***************************************************************************
// 誰か一人でも入力があるか判定
// 引数に任意のボタン定義の組み合わせを指定 -> 押しているパッドIDが帰る
// 該当なしの場合は-1を返す
// 複数パッドで入力がある場合は若い番号を優先する
// ***************************************************************************
// ===========================================================================
//! デジタル 直値(押している間ON)								PAD_DIRECT
// ===========================================================================
s32 AoPadSomeoneDirect(u16 key)
{
	for (s32 i = 0; i < AOD_PAD_PORT_MAX; ++i) {
		if (PAD_DIRECT(i) & key) {
			return i;
		}
	}
	return -1;
}

