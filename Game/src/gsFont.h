/*
	aoFontの管理を行なうモジュールです。
	aoFontの構築や解放を行なう場合は、
	必ずこのモジュールを介して行なうようにして下さい。
	aoFontはWii版でのみ有効なモジュールとなりますので、
	Wii版以外では、このモジュールは何も行ないません。
	ただし、正当な結果が返るように処理をします。
	(GsFontBuildとGsFontReleaseの間でのみGsFontIsBuildedがTRUEを返すなど)
*/

// ----- Include Files ---------------------------------------（インクルード）
// ----- Macros ------------------------------------------------（マクロ定義）
