// ===========================================================================
//	GsFontInit
/*!
	初期化開始

	@note
	アプリケーション起動時に一度だけ呼び出して下さい。\n
*/
// ===========================================================================
extern void GsFontInit(void);

// ===========================================================================
//	GsFontExit
/*!
	終了

	@note
	アプリケーション終了時に一度だけ呼び出して下さい。\n
*/
// ===========================================================================
extern void GsFontExit(void);

// ===========================================================================
//	GsFontBuild
/*!
	構築開始

	@param use_mem2	[in] 真：MEM2を使用　偽：MEM1を使用
	@note
	既に構築済み、あるいは構築中の場合は何も行ないません。\n
*/
// ===========================================================================
extern void GsFontBuild(BOOL use_mem2 = TRUE);

// ===========================================================================
//	GsFontIsBuilding
/*!
	構築中判定

	@return 真：構築中　偽：それ以外
	@note
	GsFontBuild関数で開始した構築処理が
	行なわれている最中かどうかを判定します。\n
	構築が完了した時点でFALSEを返すようになります。\n
	GsFontIsBuilded関数がTRUEを返す状態で
	この関数がTRUEを返すことはありません。\n
*/
// ===========================================================================
extern BOOL GsFontIsBuilding(void);

// ===========================================================================
//	GsFontIsBuilded
/*!
	構築済み判定

	@return 真：構築済み　偽：それ以外
	@note
	GsFontBuild関数で開始した構築処理が完了したかどうかを返します。\n
	この関数がTRUEを返す状態はAoFontIsBuilded関数が
	TRUEを返す状態と"ほぼ"一致しています。\n
*/
// ===========================================================================
extern BOOL GsFontIsBuilded(void);

// ===========================================================================
//	GsFontRelease
/*!
	解放

	@note
	aoFontモジュールの解放を行います。\n
*/
// ===========================================================================
extern void GsFontRelease(void);

