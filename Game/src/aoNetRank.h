/*
	■エラーについて
	AoNetRankStart関数を呼び出してからAoNetRankEnd関数を呼び出すまでの間は、
	AoNetRankIsError関数でエラーの発生を定期的に検知しておくようにして下さい。
	エラーの発生要因としては、通常のネットワークエラーの他に、
	不正な関数呼び出しなども含まれます。
	原則、不正な関数呼び出しを行った場合はアサートし、
	AOD_NET_RANK_ERROR_OPERATIONエラーとなります。
*/

