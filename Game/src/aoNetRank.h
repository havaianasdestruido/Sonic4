// ----- Macros ------------------------------------------------（マクロ定義）

#define AOD_NET_RANK_NAME_LEN	(16 + 1)	//!< 名前長(終端文字含む)

#define AOD_NET_RANK_FLAG_OWN	(1 <<  0)	//!< 自分のランキングデータ
#define AOD_NET_RANK_FLAG_SS	(1 <<  1)	//!< スーパーソニック使用

#define AOD_NET_RANK_OWN_NEAR	((u32)-1)	//!< 自身の周辺
#define AOD_NET_RANK_FRIENDS	((u32)-2)	//!< フレンドランキング

#define AOD_NET_RANK_RECV_MAX	(10)		//!< 最大受信データ数

// ----- Macro Functions -----------------------------------（処理マクロ定義）
// ----- Definitions -------------------------------------------（定数の宣言）

// ===========================================================================
//	enum AOE_NET_RANK_TYPE
// ---------------------------------------------------------------------------
//!	ネットワークランキングタイプ列挙
// ===========================================================================
typedef enum tag_AOE_NET_RANK_TYPE {
	AOD_NET_RANK_TYPE_TIME			= 0,	//!< タイムアタック
	AOD_NET_RANK_TYPE_SCORE,				//!< スコアアタック

	AOD_NET_RANK_TYPE_NUM,					//!< タイプ数
	AOD_NET_RANK_TYPE_NONE,					//!< 無効コード
} AOE_NET_RANK_TYPE;

// ===========================================================================
//	enum AOE_NET_RANK_REGION
// ---------------------------------------------------------------------------
//!	ネットワークランキングリージョン列挙
// ===========================================================================
typedef enum tag_AOE_NET_RANK_REGION {
	AOD_NET_RANK_REGION_JP			= 0,	//!< 日本
	AOD_NET_RANK_REGION_US,					//!< 北米
	AOD_NET_RANK_REGION_EU,					//!< 欧州
	AOD_NET_RANK_REGION_OTHER,				//!< その他

	AOD_NET_RANK_REGION_NUM,				//!< リージョン数
} AOE_NET_RANK_REGION;

// ----- Struct Definitions --------------------------------------（型の宣言）

// ===========================================================================
//	struct AOS_NET_RANK_SEND
// ---------------------------------------------------------------------------
//!	送信データ
// ===========================================================================
typedef struct tag_AOS_NET_RANK_SEND {
	union {
		u32		time;							//!< タイム
		u32		score;							//!< スコア
	};
	BOOL		ss;								//!< 真：Sソニック使用
} AOS_NET_RANK_SEND; // 8 byte

// ===========================================================================
//	struct AOS_NET_RANK_DATA
// ---------------------------------------------------------------------------
//!	ランキングデータ
// ===========================================================================
typedef struct tag_AOS_NET_RANK_DATA {
	char		name[AOD_NET_RANK_NAME_LEN];	//!< 名前(終端文字含む)
	u8			flag;							//!< フラグ
	u8			region;							//!< リージョン
	u8			pad;							//!< パディング
	u32			rrank;							//!< 実順位(0-)
	u32			rank;							//!< 順位(0-)
	union {
		u32		time;							//!< タイム
		u32		score;							//!< スコア
	};
#if _XBOX
	XUID		xuid;							//!< XUID
#endif // _XBOX
} AOS_NET_RANK_DATA; // 32 byte

