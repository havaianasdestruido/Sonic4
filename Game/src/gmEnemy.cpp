// ================================================================
// GmEnemyDefFuncSetPacketState
/*!
  エネミーダメージ喰らい処理 パケットステータス指定タイプ

  @param	match_rect	[in]	相手矩形ワーク
  @param	mine_rect	[in]	自分矩形ワーク
  @param	state		[in]	ステート GMD_ENEMY_STATE_****

  @return	GME_ENEMY_DEF_FUNC_PS_STATE

  @note
	ニトロHIT以外は、stateで指定したステータスでパケット送信します。¥n
	HIT処理内から呼び出して下さい。¥n
	送信ステータスがGMD_ENEMY_STATE_DIEの場合はgmEnemyDefaultDefFuncを使用して下さい。¥n
	ニトロHIT以外は敵死亡ステータス, HIT OFF を行いません。¥n
	体力対応はありません。
 */
// ================================================================
GME_ENEMY_DEF_FUNC_PS_STATE GmEnemyDefFuncSetPacketState(OBS_RECT_WORK *match_rect, OBS_RECT_WORK *mine_rect, u8 state)
{
	GMS_ENEMY_COM_WORK	*ene_work	= (GMS_ENEMY_COM_WORK*)mine_rect->parent_obj;
	GMS_PLAYER_WORK	*ply_work	= (GMS_PLAYER_WORK*)match_rect->parent_obj;

	if (ene_work == NULL) {
		return (GMD_ENEMY_DEF_FUNC_PS_STATE_NOHIT);
	}

	if (ply_work) {
		if (ply_work->obj.obj_type == GMD_OBJTYPE_PLAYER) {
			// テンション増加
			GmPlayerTensionEnemyGet(ply_work, GMD_PLAYER_ENEMY_TENSION);

			// パケット送信
			GmEnemyPacketSet(ene_work, ply_work, state);

			// プレイヤー跳ね返り
			GmPlayerAtkReactionInit(ply_work);

			return (GMD_ENEMY_DEF_FUNC_PS_STATE_NORMAL);
		}
		else if (ply_work->obj.parent_obj) {
			ply_work = (GMS_PLAYER_WORK *)ply_work->obj.parent_obj;

			if (ply_work->obj.obj_type == GMD_OBJTYPE_PLAYER) {	// オブジェクトの親がプレイヤーの場合
			// ニトロHIT
				// 特定の状態で死亡フラグを立てない
				if (!(ene_work->obj.move_flag & OBD_MOVE_NOCOLFIELD)) {
					ene_work->enemy_flag |= GMD_ENEMY_FLAG_DIE;
				}
				// HIT OFF
				ene_work->obj.flag |= OBD_OBJECT_NOHIT;
				ene_work->rect_work[0].flag |= OBD_RECT_NOHIT;
				ene_work->rect_work[1].flag |= OBD_RECT_NOHIT;
				ene_work->rect_work[2].flag |= OBD_RECT_NOHIT;

				// テンション増加
				GmPlayerTensionEnemyGet(ply_work, GMD_PLAYER_ENEMY_TENSION);
				gmEnemyNitroDieInit(ene_work, &ply_work->obj);
				if (ply_work->player_flag & GMD_PLF_NITRO) {
					// ニトロ中ならヒットストップタイマ設定
					ply_work->obj.hitstop_timer	= 4 * FX32_ONE;
					ply_work->obj.vib_timer		= 4 * FX32_ONE;
					ene_work->obj.hitstop_timer	= 4 * FX32_ONE;
					ene_work->obj.vib_timer		= 4 * FX32_ONE;
				}

				// パケット送信
				GmEnemyPacketSet(ene_work, ply_work, GMD_ENEMY_STATE_DIE);
				return (GMD_ENEMY_DEF_FUNC_PS_STATE_NITRO);
			}
		}
	}
	return (GMD_ENEMY_DEF_FUNC_PS_STATE_NOHIT);
}
