// ----- Struct Definitions --------------------------------------（型の宣言）

// ***************************************************************************
// 差分情報ファイル(*.df)
// ***************************************************************************
// ===========================================================================
//	struct DF_HEADER
// ---------------------------------------------------------------------------
//!	差分情報ファイルヘッダ
// ===========================================================================
typedef struct tag_DF_HEADER {
	Uint32			block_num;			//!< ブロック数(0 - 2047)
} DF_HEADER; // 4byte

// ===========================================================================
//	struct DF_BLOCK
// ---------------------------------------------------------------------------
//!	差分情報ブロック
// ===========================================================================
typedef struct tag_DF_BLOCK {
	Uint8			df[8][8][8];		//!< 差分情報
} DF_BLOCK; // 512byte


// ***************************************************************************
// 属性情報ファイル(*.at)
// ***************************************************************************
// ===========================================================================
//	struct AT_HEADER
// ---------------------------------------------------------------------------
//!	属性情報ファイルヘッダ
// ===========================================================================
typedef struct tag_AT_HEADER {
	Uint32			block_num;			//!< ブロック数(0 - 2047)
} AT_HEADER; // 4byte

// ===========================================================================
//	struct AT_BLOCK
// ---------------------------------------------------------------------------
//!	属性情報ブロック
// ===========================================================================
typedef struct tag_AT_BLOCK {
	Uint8			at[8][8];			//!< 属性情報
} AT_BLOCK; // 64byte


// ***************************************************************************
// 角度情報ファイル(*.di)
// ***************************************************************************
// ===========================================================================
//	struct DI_HEADER
// ---------------------------------------------------------------------------
//!	角度情報ファイルヘッダ
// ===========================================================================
typedef struct tag_DI_HEADER {
	Uint32			block_num;			//!< ブロック数(0 - 2047)
} DI_HEADER; // 4byte

// ===========================================================================
//	struct DI_BLOCK
// ---------------------------------------------------------------------------
//!	角度情報ブロック
// ===========================================================================
typedef struct tag_DI_BLOCK {
	Uint8			di[8][8];			//!< 角度情報
} DI_BLOCK; // 64byte


// ***************************************************************************
// マップ情報ファイル(*.mp)
// ***************************************************************************
// ===========================================================================
//	struct MP_HEADER
// ---------------------------------------------------------------------------
//!	マップ情報ファイルヘッダ
// ===========================================================================
typedef struct tag_MP_HEADER {
	Uint16			map_w;				//!< ブロック単位でのマップ横サイズ
	Uint16			map_h;				//!< ブロック単位でのマップ縦サイズ
} MP_HEADER; // 4byte

// ===========================================================================
//	struct MP_BLOCK
// ---------------------------------------------------------------------------
//!	マップ情報ブロック
// ===========================================================================
typedef struct tag_MP_BLOCK {
#if _PS3 | _XBOX | _WII
	Uint16	flip_v	: 1;				//!< 縦フリップ
	Uint16	flip_h	: 1;				//!< 横フリップ
	Uint16	rot		: 2;				//!< 90度単位の回転量
	Uint16	id		: 12;				//!< ID
#else
	Uint16	id		: 12;				//!< ID
	Uint16	rot		: 2;				//!< 90度単位の回転量
	Uint16	flip_h	: 1;				//!< 横フリップ
	Uint16	flip_v	: 1;				//!< 縦フリップ
#endif
} MP_BLOCK; // 2byte


// ***************************************************************************
// マップ描画情報ファイル(*.md)
// ***************************************************************************
// ===========================================================================
//	struct MD_HEADER
// ---------------------------------------------------------------------------
//!	マップ描画情報ファイルヘッダ
// ===========================================================================
typedef struct tag_MD_HEADER {
	Uint16			map_w;				//!< ブロック単位でのマップ横サイズ
	Uint16			map_h;				//!< ブロック単位でのマップ縦サイズ
} MD_HEADER; // 4byte

// ===========================================================================
//	struct MD_BLOCK
// ---------------------------------------------------------------------------
//!	マップ描画情報ブロック
// ===========================================================================
typedef struct tag_MD_BLOCK {
#if _PS3 | _XBOX | _WII
	Sint8			ofst_y	: 4;		//!< 描画ブロック縦オフセット(-8 - 7)
	Sint8			ofst_x	: 4;		//!< 描画ブロック横オフセット(-8 - 7)
#else
	Sint8			ofst_x	: 4;		//!< 描画ブロック横オフセット(-8 - 7)
	Sint8			ofst_y	: 4;		//!< 描画ブロック縦オフセット(-8 - 7)
#endif
} MD_BLOCK; // 1byte


// ***************************************************************************
// イベント情報ファイル(*.ev)
// ***************************************************************************
// ===========================================================================
//	struct EV_HEADER
// ---------------------------------------------------------------------------
//!	イベント情報ファイルヘッダ
// ===========================================================================
typedef struct tag_EV_HEADER {
	Uint16			map_w;				//!< ブロック単位でのマップ横サイズ
	Uint16			map_h;				//!< ブロック単位でのマップ縦サイズ
} EV_HEADER; // 4byte

// ===========================================================================
//	struct EV_OFFSET
// ---------------------------------------------------------------------------
//!	イベント情報ブロックオフセット
// ===========================================================================
typedef struct tag_EV_OFFSET {
	Uint32			ofst;				//!< ブロック情報へのオフセット
} EV_OFFSET; // 4byte

// ===========================================================================
//	struct EV_BLOCK
// ---------------------------------------------------------------------------
//!	イベント情報ブロック
// ===========================================================================
typedef struct tag_EV_BLOCK {
	Uint16			ev_num;				//!< イベント数
} EV_BLOCK; // 2byte

// ===========================================================================
//	struct EV_INFO
// ---------------------------------------------------------------------------
//!	イベント情報
// ===========================================================================
typedef struct tag_EV_INFO {
	Uint8			x;					//!< X座標
	Uint8			y;					//!< Y座標
	Uint16			id;					//!< ID
	Uint16			flag;				//!< フラグ
	Sint8			rect_x;				//!< 矩形左上X座標
	Sint8			rect_y;				//!< 矩形左上Y座標
	Uint8			rect_w;				//!< 矩形横サイズ
	Uint8			rect_h;				//!< 矩形縦サイズ
	Uint16			user;				//!< ユーザパラメータ
} EV_INFO; // 12byte


// ***************************************************************************
// リング情報ファイル(*.rg)
// ***************************************************************************
// ===========================================================================
//	struct RG_HEADER
// ---------------------------------------------------------------------------
//!	リング情報ファイルヘッダ
// ===========================================================================
typedef struct tag_RG_HEADER {
	Uint16			map_w;				//!< ブロック単位でのマップ横サイズ
	Uint16			map_h;				//!< ブロック単位でのマップ縦サイズ
} RG_HEADER; // 4byte

// ===========================================================================
//	struct RG_OFFSET
// ---------------------------------------------------------------------------
//!	リング情報ブロックオフセット
// ===========================================================================
typedef struct tag_RG_OFFSET {
	Uint32			ofst;				//!< ブロック情報へのオフセット
} RG_OFFSET; // 4byte

// ===========================================================================
//	struct RG_BLOCK
// ---------------------------------------------------------------------------
//!	リング情報ブロック
// ===========================================================================
typedef struct tag_RG_BLOCK {
	Uint16			rg_num;				//!< リング数
} RG_BLOCK; // 2byte

// ===========================================================================
//	struct RG_INFO
// ---------------------------------------------------------------------------
//!	リング情報
// ===========================================================================
typedef struct tag_RG_INFO {
	Uint8			x;					//!< X座標
	Uint8			y;					//!< Y座標
} RG_INFO; // 2byte


// ***************************************************************************
// 装飾情報ファイル(*.dc)
// ***************************************************************************
// ===========================================================================
//	struct DC_HEADER
// ---------------------------------------------------------------------------
//!	装飾情報ファイルヘッダ
// ===========================================================================
typedef struct tag_DC_HEADER {
	Uint16			map_w;				//!< ブロック単位でのマップ横サイズ
	Uint16			map_h;				//!< ブロック単位でのマップ縦サイズ
} DC_HEADER; // 4byte

// ===========================================================================
//	struct DC_OFFSET
// ---------------------------------------------------------------------------
//!	装飾情報ブロックオフセット
// ===========================================================================
typedef struct tag_DC_OFFSET {
	Uint32			ofst;				//!< ブロック情報へのオフセット
} DC_OFFSET; // 4byte

// ===========================================================================
//	struct DC_BLOCK
// ---------------------------------------------------------------------------
//!	装飾情報ブロック
// ===========================================================================
typedef struct tag_DC_BLOCK {
	Uint16			dc_num;				//!< 装飾数
} DC_BLOCK; // 2byte

// ===========================================================================
//	struct DC_INFO
// ---------------------------------------------------------------------------
//!	装飾情報
// ===========================================================================
typedef struct tag_DC_INFO {
	Uint8			x;					//!< X座標
	Uint8			y;					//!< Y座標
	Uint16			id;					//!< ID
} DC_INFO; // 4byte

