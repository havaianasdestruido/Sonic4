/*!
	@page map

	@section map_info 概要
	マップは、サイズ64x64のブロックにより構成されています。\n
	ブロックをマップ左上から右下へ向けて
	横方向優先で配置したものがマップ情報となります。\n

	ブロックには、当たり情報や角度情報などのデータと見た目のデータの2種類あり、
	それぞれの情報へのインデックス配列としてマップが構成されます。\n

	ブロックには、差分情報、属性情報、角度情報の3つの情報があり、
	それぞれ別ファイルで扱われます。
	(3つのファイルをセットで扱う必要があります。)\n
	各情報は、サイズ8x8の単位で扱われ、その単位の8x8配列として構成されます。\n

	マップ内のイベントデータは、サイズ256x256のブロックに分けて管理されます。\n
	イベント情報、リング情報、装飾情報の3種類あり、
	それぞれ別ファイルで扱われます。\n
	イベントデータの座標は、ブロック内の座標として扱われます。\n


	@section map_df 差分情報ファイル
	マップの当たり情報を格納したファイルです。\n
	1つのブロックは、8x8の単位のデータを、64個保持しており、
	縦方向と横方向の、当たりピクセルと非当たりピクセルの情報が
	格納されています。\n
	ファイル先頭にブロック数が格納されており、
	その後ろに、ブロック単位の差分情報がブロック数分格納されています。\n


	@section map_at 属性情報ファイル
	マップの属性情報を格納したファイルです。\n
	1つのブロックは、8x8の単位のデータを、64個保持しています。\n
	ファイル先頭にブロック数が格納されており、
	その後ろに、ブロック単位の属性情報がブロック数分格納されています。\n


	@section map_di 角度情報ファイル
	マップの角度情報を格納したファイルです。\n
	1つのブロックは、8x8の単位のデータを、64個保持しています。\n
	ファイル先頭にブロック数が格納されており、
	その後ろに、ブロック単位の角度情報がブロック数分格納されています。\n


	@section map_mp マップ情報ファイル
	マップのブロック配置を格納したファイルです。\n
	保持するデータは、ブロックIDと、ブロックの反転＆回転情報となります。\n
	このファイルは、差分情報や属性情報のインデックスとして使用する場合や
	表示モデルのインデックスで使用する場合など、
	複数の目的で使用されます。\n
	ファイル先頭に縦横のブロック数が格納されており、
	その後ろに、ブロック情報がブロック数分格納されています。\n
	現状のブロック情報の構造上、あつかえる最大ブロック数は2048となります。\n


	@section map_md マップ描画情報ファイル
	マップの描画用情報を格納したファイルです。\n
	マップ描画の際に、あるブロックのモデルが複数ブロックにまたがる形で
	配置されている場合に、そのブロックが画面外に出て描画されなくなると
	不都合がある場合があります。\n
	この問題を解決するために、
	「このブロックの表示はどのブロックに依存しているか」
	という情報がブロック単位で格納されています。\n


	@section map_ev イベント情報ファイル
	マップ上に配置されたイベントの情報を格納したファイルです。\n
	マップ情報とは異なり、サイズ256x256のブロック単位での構成となります。\n
	イベント自体は別で管理されており、イベントのIDが格納されています。\n
	ファイル先頭に縦横のブロック数が格納されており、
	その後ろに、ブロック情報へのオフセットの配列が格納されています。\n
	1つのブロック情報は、先頭にイベント数が格納され、
	その後ろに、イベント数分のイベント情報が格納されています。\n


	@section map_rg リング情報ファイル
	マップ上に配置されたリングの情報を格納したファイルです。\n
	マップ情報とは異なり、サイズ256x256のブロック単位での構成となります。\n
	ファイル先頭に縦横のブロック数が格納されており、
	その後ろに、ブロック情報へのオフセットの配列が格納されています。\n
	1つのブロック情報は、先頭にリング数が格納され、
	その後ろに、リング数分のリング情報が格納されています。\n


	@section map_dc 装飾情報ファイル
	マップ上に配置された装飾の情報を格納したファイルです。\n
	マップ情報とは異なり、サイズ256x256のブロック単位での構成となります。\n
	装飾情報自体は別で管理され、装飾のIDが格納されています。\n
	ファイル先頭に縦横のブロック数が格納されており、
	その後ろに、ブロック情報へのオフセットの配列が格納されています。\n
	1つのブロック情報は、先頭に装飾数が格納され、
	その後ろに、装飾数分の装飾情報が格納されています。\n


	@sa map.h
*/
#pragma once

// ----- Include Files ---------------------------------------（インクルード）
// ----- Macros ------------------------------------------------（マクロ定義）
